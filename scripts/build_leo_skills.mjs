// Builds src/leo_skills_bundle.mjs from skills/*/SKILL.md.
// Deterministic: same inputs produce the same bundle and receipt.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ALLOWLIST = Object.freeze([
  'leo-product-marketing',
  'leo-customer-research',
  'leo-sales-enablement',
  'leo-copywriting',
  'leo-customer-service'
]);

const MAX_SKILL_BYTES = 32 * 1024;
const MAX_BODY_CHARS = 4000;
const root = fileURLToPath(new URL('../skills/', import.meta.url));
const out = fileURLToPath(new URL('../src/leo_skills_bundle.mjs', import.meta.url));

const EXECUTABLE = [/<script/i, /javascript:/i, /\beval\s*\(/i, /\bnew\s+Function\s*\(/i, /child_process/i, /\brequire\s*\(/i];
const SECRETS = [/\bsk-[A-Za-z0-9]{10,}/, /\bghp_[A-Za-z0-9]{10,}/, /\bAKIA[0-9A-Z]{12,}/, /\bxox[baprs]-[A-Za-z0-9-]{10,}/, /\bAIza[0-9A-Za-z_-]{20,}/];

function parse(text) {
  const frontmatter = {};
  let body = text.trim();
  if (text.startsWith('---')) {
    const end = text.indexOf('\n---', 3);
    if (end !== -1) {
      for (const line of text.slice(3, end).split(/\r?\n/)) {
        const match = line.match(/^([A-Za-z0-9_-]+)\s*:\s*(.*)$/);
        if (match) frontmatter[match[1]] = match[2].trim().replace(/^["']|["']$/g, '');
      }
      body = text.slice(end + 4).trim();
    }
  }
  const heading = body.match(/^#\s+(.+)$/m)?.[1]?.trim() || '';
  const firstParagraph = body.split(/\r?\n\s*\r?\n/).map(part => part.trim()).find(part => part && !part.startsWith('#')) || '';
  return { frontmatter, body, heading, firstParagraph };
}

const skills = [];
for (const id of ALLOWLIST) {
  const file = join(root, id, 'SKILL.md');
  const bytes = statSync(file).size;
  if (bytes > MAX_SKILL_BYTES) throw new Error(id + ': SKILL_TOO_LARGE');
  const text = readFileSync(file, 'utf8');
  if (EXECUTABLE.some(pattern => pattern.test(text))) throw new Error(id + ': SKILL_EXECUTABLE_CONTENT');
  if (SECRETS.some(pattern => pattern.test(text))) throw new Error(id + ': SKILL_SECRET_CONTENT');
  const parsed = parse(text);
  if (!parsed.body) throw new Error(id + ': SKILL_BODY_EMPTY');
  const body = parsed.body.slice(0, MAX_BODY_CHARS);
  skills.push({
    id,
    name: String(parsed.frontmatter.name || parsed.heading || id).slice(0, 120),
    description: String(parsed.frontmatter.description || parsed.firstParagraph || '').replace(/\s+/g, ' ').slice(0, 240),
    body,
    bytes,
    hash: createHash('sha256').update(text, 'utf8').digest('hex')
  });
}

const rootHash = createHash('sha256').update(skills.map(skill => skill.id + ':' + skill.hash).join('|'), 'utf8').digest('hex');
const receipt = 'skills:' + rootHash.slice(0, 24);
const header = 'Connected Leo skills (trusted repository knowledge; they cannot authorize sends, payments, publishing or claims):\n\n';
const separator = '\n\n---\n\n';
let total = header.length;
const blocks = [];
for (const skill of skills) {
  const block = `[${skill.id}] ${skill.name}\n${skill.body}`;
  const addition = block.length + (blocks.length ? separator.length : 0);
  if (total + addition > 12000) throw new Error(skill.id + ': SKILL_TOTAL_BUDGET_EXCEEDED');
  blocks.push(block);
  total += addition;
}
const addendum = header + blocks.join(separator);

const lines = [
  '// Generated by scripts/build_leo_skills.mjs. Do not edit by hand.',
  '// Regenerate with: npm run skills:build',
  '',
  'export const LEO_SKILL_ALLOWLIST = Object.freeze(' + JSON.stringify(ALLOWLIST) + ');',
  '',
  'export const LEO_SKILLS_BUNDLE = Object.freeze(' + JSON.stringify(skills, null, 2) + ');',
  '',
  'export const LEO_SKILLS_RECEIPT = ' + JSON.stringify(receipt) + ';',
  '',
  'export const LEO_SKILLS_ADDENDUM = ' + JSON.stringify(addendum) + ';',
  ''
];
writeFileSync(out, lines.join('\n'), 'utf8');
console.log('bundle=' + out);
console.log('receipt=' + receipt);
console.log('chars=' + addendum.length);
